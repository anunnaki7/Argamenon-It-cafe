export type Dict = typeof sr;

const LangContext = createContext<{
  lang: "sr" | "en";
  setLang: (l: "sr" | "en") => void;
  t: Dict;
}>({ lang: "sr", setLang: () => {}, t: sr });

/* keep SEO tags in sync with the active language */
function syncMetaTags(dict: Dict) {
  const setMeta = (attr: "name" | "property", key: string, content: string) => {
    const el = document.head.querySelector<HTMLMetaElement>(`meta[${attr}="${key}"]`);
    if (el) el.setAttribute("content", content);
  };
  document.title = dict.meta.title;
  setMeta("name", "description", dict.meta.description);
  setMeta("property", "og:title", dict.meta.title);
  setMeta("property", "og:description", dict.meta.description);
  setMeta("property", "og:locale", dict.meta.ogLocale);
  setMeta("name", "twitter:title", dict.meta.title);
  setMeta("name", "twitter:description", dict.meta.description);
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<"sr" | "en">("sr");
  const t = lang === "sr" ? sr : en;

  const setLang = (l: "sr" | "en") => {
    setLangState(l);
    document.documentElement.lang = l;
  };

  useEffect(() => {
    syncMetaTags(t);
  }, [t]);

  return (
    <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
